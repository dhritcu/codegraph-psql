#!/usr/bin/env node
/**
 * Regenerate src/resolution/postgres-builtins.ts from PostgreSQL's own catalog:
 *
 *   curl -sfLO https://raw.githubusercontent.com/postgres/postgres/REL_18_3/src/include/catalog/pg_proc.dat
 *   node scripts/gen-postgres-builtins.mjs pg_proc.dat REL_18_3 [--write]
 *
 * Every `proname` in pg_proc.dat is a function every database has, so a call
 * to one names nothing the project declares. The SQL-standard forms the
 * grammar spells like calls but pg_proc has no row for (`coalesce`,
 * `nullif`, `greatest`, `least`) are added by hand.
 *
 * Prints the module; --write puts it in place instead.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MODULE = path.join(ROOT, 'src', 'resolution', 'postgres-builtins.ts');
const SQL_SYNTAX_FUNCTIONS = ['coalesce', 'nullif', 'greatest', 'least'];

const [source, tag] = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const write = process.argv.includes('--write');
if (!source || !tag || !fs.existsSync(source)) {
  console.error('usage: gen-postgres-builtins.mjs <pg_proc.dat> <source tag, e.g. REL_18_3> [--write]');
  process.exit(2);
}

const names = new Set(SQL_SYNTAX_FUNCTIONS);
for (const m of fs.readFileSync(source, 'utf8').matchAll(/\bproname => '([^']+)'/g)) names.add(m[1]);
if (names.size < 1000) {
  console.error(`only ${names.size} names read from ${source}: not a pg_proc.dat`);
  process.exit(1);
}

const lines = [];
let line = '';
for (const name of [...names].sort()) {
  if (line && line.length + name.length + 1 > 96) {
    lines.push(line);
    line = '';
  }
  line = line ? `${line} ${name}` : name;
}
if (line) lines.push(line);

const out = `/**
 * The functions every PostgreSQL database has: a call to one names nothing a
 * project declares, so it gets no edge.
 *
 * Generated by scripts/gen-postgres-builtins.mjs from PostgreSQL's
 * src/include/catalog/pg_proc.dat at ${tag} (every \`proname\`), plus the
 * SQL-standard forms written like calls that have no pg_proc row
 * (${SQL_SYNTAX_FUNCTIONS.join(', ')}). Do not edit by hand.
 */
const NAMES = \`
${lines.join('\n')}
\`;

export const POSTGRES_BUILTIN_FUNCTIONS: ReadonlySet<string> = new Set(NAMES.split(/\\s+/).filter(Boolean));
`;

if (write) {
  fs.writeFileSync(MODULE, out);
  console.error(`wrote ${names.size} names to ${path.relative(ROOT, MODULE)}`);
} else {
  process.stdout.write(out);
}
